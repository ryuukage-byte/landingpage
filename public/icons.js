  function validate() {
    for (const [name, g] of Object.entries(ICONS)) {
      if (g.length !== 12 || g.some(r => r.length !== 12 || /[^.#]/.test(r))) throw new Error('Bad icon grid: ' + name);
    }
  }

  // Row runs become one path segment each — small output, crisp at integer scales.
  function iconPath(name) {
    let d = '';
    if (!ICONS[name]) return d; // unknown name → empty icon, never break the caller
    ICONS[name].forEach((row, y) => {
      for (let x = 0; x < 12;) {
        if (row[x] !== '#') { x++; continue; }
        const s = x;
        while (x < 12 && row[x] === '#') x++;
        d += `M${s} ${y}h${x - s}v1h-${x - s}z`;
      }
    });
    return d;
  }

  function iconSVG(name, size, label) {
    size = size || 24;
    const a11y = label ? `role="img" aria-label="${label}"` : 'aria-hidden="true" focusable="false"';
    return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 12 12" width="${size}" height="${size}" fill="currentColor" shape-rendering="crispEdges" ${a11y}><path d="${iconPath(name)}"/></svg>`;
  }

  validate();
